// Image paths are stored relative to this JavaScript file, not the page URL.
// This prevents images from breaking when the page is served from a nested
// directory. Missing files are also logged so their exact path is visible.
const partyScriptUrl = document.currentScript?.src;
const partyImageBase = partyScriptUrl
  ? new URL(".", partyScriptUrl)
  : new URL(".", document.baseURI);

for (const item of [...window.PARTY.fame, ...window.PARTY.photos]) {
  item.src = new URL(item.src, partyImageBase).href;
}
window.PARTY.imageFallback = new URL(window.PARTY.imageFallback, partyImageBase).href;

// Keep a broken image from leaving an empty tile if an optional photo is missing.
document.addEventListener("error", (event) => {
  const image = event.target;
  if (image instanceof HTMLImageElement && !image.dataset.fallbackApplied) {
    console.warn("Party image failed to load:", image.src);
    image.dataset.fallbackApplied = "true";
    image.src = window.PARTY.imageFallback;
  }
}, true);
